// semantic-release configuration. A green push to main whose release gate opens (a pull request merged since the last
// release tag has the label cut-release or security, see eng/release-gate.mjs), or a hand-started run of the Release
// workflow, looks at the commits since the last release tag and, when one of them is a feat / fix / perf / revert (or a
// breaking change), releases the next version: the binaries for linux-x64, osx-arm64 and win-x64 (built with that
// version by .github/workflows/build-binaries.yml), their SBOMs and SHA256SUMS on a GitHub release v<version>, the
// tag, CHANGELOG.md (only with the GitHub App, see below) and the packages in eriklieben/packages. How to write the
// commits: docs/development/README.md, "Commit messages and releases". How a release works: docs/releasing.md.
//
//   pnpm exec semantic-release --dry-run --no-ci     what would the next release be? (needs GITHUB_TOKEN and push access)
//
// Commits not in this format (plain sentences such as "Add a settings page") have no type: the analyzer ignores them,
// so they never release anything and aren't in the notes.

// The Angular commit format (type(scope): subject), plus the `!` breaking-change marker from Conventional Commits
// (`feat!: ...`, `fix(pty)!: ...`). Same as the conventionalcommits preset's parser, plus the plural `BREAKING CHANGES`
// footer that the Angular guidelines also allow. Shared by the analyzer and the notes generator so both see the same
// commits.
const parserOpts = {
  headerPattern: /^(\w*)(?:\((.*)\))?!?: (.*)$/,
  breakingHeaderPattern: /^(\w*)(?:\((.*)\))?!: (.*)$/,
  headerCorrespondence: ["type", "scope", "subject"],
  noteKeywords: ["BREAKING CHANGE", "BREAKING CHANGES", "BREAKING-CHANGE"],
};

// Release-notes sections (conventional-changelog-conventionalcommits; the first matching entry wins, so the `deps`
// entries come before plain `fix` / `build`). Every release is a `##` heading, breaking changes get their own
// "⚠ BREAKING CHANGES" section and scopes are shown in bold (`**render:** ...`). Hidden types don't appear in the notes
// (they don't release anything either), unless they carry a breaking change.
const presetConfig = {
  types: [
    { type: "feat", section: "Features" },
    { type: "fix", scope: "deps", section: "Dependencies" },
    { type: "build", scope: "deps", section: "Dependencies" },
    { type: "fix", section: "Bug Fixes" },
    { type: "perf", section: "Performance" },
    { type: "revert", section: "Reverts" },
    { type: "docs", section: "Documentation", hidden: true },
    { type: "style", section: "Styles", hidden: true },
    { type: "chore", section: "Miscellaneous", hidden: true },
    { type: "refactor", section: "Refactoring", hidden: true },
    { type: "test", section: "Tests", hidden: true },
    { type: "build", section: "Build", hidden: true },
    { type: "ci", section: "CI", hidden: true },
  ],
};
// The preset orders sections by their first entry in `types`, which would put Dependencies above Bug Fixes.
const sectionOrder = ["Features", "Bug Fixes", "Performance", "Reverts", "Dependencies"];
const rank = (title) => (sectionOrder.includes(title) ? sectionOrder.indexOf(title) : sectionOrder.length);
const writerOpts = { commitGroupsSort: (a, b) => rank(a.title) - rank(b.title) };

// Kept at the top of CHANGELOG.md; @semantic-release/changelog adds each release below it. Must match the file.
const changelogTitle = `# Changelog

All notable changes to erikterm are documented here. This file is generated by
[semantic-release](https://github.com/semantic-release/semantic-release) from the commit messages (see
[docs/development/README.md](docs/development/README.md#commit-messages-and-releases)): don't edit it by hand, write a
good commit message instead. Versions follow [Semantic Versioning](https://semver.org/spec/v2.0.0.html).`;

// ERIKTERM_RELEASE_COMMIT=api: set by release.yml when the token of the GitHub App (variable RELEASE_APP_ID, secret
// RELEASE_APP_PRIVATE_KEY) was made. Then CHANGELOG.md is updated and committed through the GitHub API by
// eng/release-commit.mjs: GitHub signs that commit ("Verified"), and the tag goes on it. Without the App (and in local
// dry runs) there is no release commit at all, never an unverified push to main: the tag goes on the released commit
// itself and the notes are only on the GitHub release. erikterm has no version in its source to bump (the version is
// passed to the build, see build/BuildInfo.targets), so CHANGELOG.md is the only file a release commits.
const withReleaseCommit = process.env.ERIKTERM_RELEASE_COMMIT === "api";
const releaseCommit = withReleaseCommit
  ? [
      ["@semantic-release/changelog", { changelogFile: "CHANGELOG.md", changelogTitle }],
      [
        "./eng/release-commit.mjs",
        { assets: ["CHANGELOG.md"], message: "chore(release): ${nextRelease.version} [skip ci]\n\n${nextRelease.notes}" },
      ],
    ]
  : [];

// ERIKTERM_FIRST_RELEASE=true: set by release.yml for its input first_release, only for the very first release of the
// repository (while there is no v* tag yet). eng/first-release.mjs then asks for a release whatever the commit types
// are, and semantic-release's first release is 1.0.0. Never listed otherwise.
const firstRelease = process.env.ERIKTERM_FIRST_RELEASE === "true" ? ["./eng/first-release.mjs"] : [];

export default {
  // main is the only release branch: a breaking change -> major, feat -> minor, fix / perf / revert -> patch.
  // build.yml and release.yml release main only.
  branches: ["main"],
  tagFormat: "v${version}",
  plugins: [
    [
      "@semantic-release/commit-analyzer",
      {
        preset: "conventionalcommits",
        presetConfig,
        parserOpts,
        // The analyzer's defaults: a breaking change -> major, feat -> minor, fix / perf / revert -> patch; docs, chore,
        // refactor, test, ci, build and style -> no release, whatever their scope.
      },
    ],
    ...firstRelease,
    [
      "@semantic-release/release-notes-generator",
      {
        preset: "conventionalcommits",
        presetConfig,
        parserOpts,
        writerOpts,
      },
    ],
    [
      // verifyRelease runs once the next version is known, also in a dry run:
      // - in the Release workflow's `version` job (a dry run) it hands the version to the build jobs (GITHUB_OUTPUT);
      // - in its `release` job it checks that the version is still the one the binaries were built with
      //   (ERIKTERM_RELEASE_VERSION) and that every asset is in dist/, before anything is tagged or published.
      "@semantic-release/exec",
      { verifyReleaseCmd: "node eng/release-assets.mjs verify ${nextRelease.version} --dry-run=${options.dryRun}" },
    ],
    ...releaseCommit,
    [
      "@semantic-release/github",
      {
        // dist/ is filled by release.yml from the build jobs' artifacts, plus SHA256SUMS (eng/release-assets.mjs).
        assets: [
          { path: "dist/erikterm-linux-x64.tar.gz", label: "Linux x64 (tar.gz)" },
          { path: "dist/erikterm-osx-arm64.tar.gz", label: "macOS Apple silicon (tar.gz)" },
          { path: "dist/erikterm-win-x64.zip", label: "Windows x64 (zip)" },
          { path: "dist/erikterm-win-x64-setup.exe", label: "Windows x64 installer, no administrator rights needed" },
          { path: "dist/*.spdx.json", label: "SBOM (SPDX 2.3) of a download" },
          { path: "dist/SHA256SUMS", label: "SHA256SUMS" },
        ],
        // Defaults kept: released pull requests and issues get a comment and the label `released`, and a failed
        // release opens one issue ("The automated release is failing") that the next successful release closes. Set
        // successComment / failComment to false here if that gets noisy.
      },
    ],
  ],
};
